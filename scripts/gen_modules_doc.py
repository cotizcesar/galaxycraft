#!/usr/bin/env python3
"""Write engine-rust/docs/MODULES.md: every source file, its size and the
first line of its `//!` doc, so an agent can find code without opening big
files.  Wave block directories are summarised, not listed file by file."""
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "engine-rust" / "src"
OUT = ROOT / "engine-rust" / "docs" / "MODULES.md"
WAVE = re.compile(r"^(.*?)/(w\d\d|batches)/[^/]+\.rs$")


def doc(p: Path) -> str:
    for line in p.read_text(encoding="utf-8", errors="ignore").splitlines()[:12]:
        if line.startswith("//!"):
            return line[3:].strip().replace("|", "\\|")
    return ""


def main() -> None:
    rows, waves = [], defaultdict(lambda: [0, 0])
    for p in sorted(SRC.rglob("*.rs")):
        rel = p.relative_to(SRC).as_posix()
        n = sum(1 for _ in p.open(encoding="utf-8", errors="ignore"))
        m = WAVE.match(rel)
        if m and not rel.endswith("mod.rs"):
            waves[m.group(1)][0] += 1
            waves[m.group(1)][1] += n
            continue
        if m:
            continue
        rows.append((rel, n, doc(p)))
    text = [
        "# Module map",
        "",
        "Generated by `scripts/gen_modules_doc.py`; do not edit by hand.",
        "Sizes are lines.  Find a function with `rg -n 'fn name' engine-rust/src`.",
        "",
        "| file | lines | contents |",
        "|---|---|---|",
    ]
    text += [f"| `{r}` | {n} | {d} |" for r, n, d in rows]
    text += ["", "## Wave blocks", "", "| directory | files | lines |", "|---|---|---|"]
    text += [f"| `{d}/wNN/` | {c} | {n} |" for d, (c, n) in sorted(waves.items())]
    OUT.write_text("\n".join(text) + "\n")
    print(f"wrote {OUT}: {len(rows)} files, {sum(c for c, _ in waves.values())} wave blocks")


if __name__ == "__main__":
    main()
