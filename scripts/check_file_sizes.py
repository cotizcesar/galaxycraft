#!/usr/bin/env python3
"""Fail when a Rust source file grows past the line limit.

Hand-written files stay under LIMIT lines.  Files that are larger today are
listed in engine-rust/docs/large-files.txt with their current size; that
list may only shrink (a listed file may not grow, and new entries are not
allowed).  Wave block files (src/<module>/wNN/aNN.rs and friends) are
generated by the merge and are exempt.

    python3 scripts/check_file_sizes.py            # check
    python3 scripts/check_file_sizes.py --update   # rewrite the list after shrinking
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "engine-rust" / "src"
LIST = ROOT / "engine-rust" / "docs" / "large-files.txt"
LIMIT = 1500
WAVE = re.compile(r"/(w\d\d|translated|batches)/[^/]+\.rs$")


def sizes() -> dict[str, int]:
    out = {}
    for p in sorted(SRC.rglob("*.rs")):
        rel = p.relative_to(ROOT).as_posix()
        if WAVE.search("/" + rel):
            continue
        out[rel] = sum(1 for _ in p.open(encoding="utf-8", errors="ignore"))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--update", action="store_true")
    a = ap.parse_args()
    now = sizes()
    big = {f: n for f, n in now.items() if n > LIMIT}
    allowed = {}
    if LIST.exists():
        for line in LIST.read_text().splitlines():
            if line and not line.startswith("#"):
                f, n = line.split()
                allowed[f] = int(n)
    if a.update:
        LIST.write_text(
            "# Files over the line limit, with the size they may not exceed.\n"
            "# Only shrink this list (scripts/check_file_sizes.py --update).\n"
            + "".join(f"{f} {n}\n" for f, n in sorted(big.items()))
        )
        print(f"wrote {LIST} ({len(big)} files)")
        return 0
    bad = []
    for f, n in big.items():
        if f not in allowed:
            bad.append(f"{f}: {n} lines (limit {LIMIT}, not on the exception list)")
        elif n > allowed[f]:
            bad.append(f"{f}: {n} lines (allowed {allowed[f]}; it may only shrink)")
    for line in bad:
        print(line)
    print("ok" if not bad else f"{len(bad)} file(s) over the limit")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
